import LZString from 'lz-string';
const parseStoredJson = <T,>(raw: string): T => { try { return JSON.parse(raw); } catch { return JSON.parse(LZString.decompressFromUTF16(raw)); } };
import { expect, test } from '@playwright/test';
import { seedWorkspace } from './support/workspaceSeed';
const smoke = (page: import('@playwright/test').Page, id: string) => page.locator(`[data-smoke="${id}"]`);
test('site cost allowances, allocation, clearance and land-offer disclosure persist', async ({ page, context }) => {
  await seedWorkspace(page);
  await page.goto('/');
  await smoke(page, 'rail-appraisals').click();
  await smoke(page, 'appraisals-new-house').click();
  await smoke(page, 'appraisals-new-name').fill('Site register review');
  await smoke(page, 'appraisals-new-calculation-KNOWN_LAND_PROFIT_ON_GDV').check();
  await smoke(page, 'appraisals-new-create').click();
  await smoke(page, 'appraisals-house-stage-abnormal-works').first().click();
  const register = smoke(page, 'appraisals-abnormals');
  await expect(register).toContainText('To be assessed: 15');
  await register.getByLabel('Abnormals base allowance').fill('10000');
  await register.getByLabel('Abnormals base allowance').press('Tab');
  const card = page.locator('[data-site-cost-id="site-checklist-contamination"]');
  await card.getByLabel('Abnormal amount').fill('25000');
  await card.getByLabel('Abnormal amount').press('Tab');
  await card.getByLabel('Allocation for Contamination and remediation').selectOption('INFRASTRUCTURE');
  await card.getByLabel('Status for Contamination and remediation').selectOption('KNOWN');
  await card.getByLabel('Include in land offer').check();
  await card.getByText('Assessment and change history', { exact: true }).click();
  await card.getByLabel('Responsible person').fill('Review QS');
  await card.getByLabel('Responsible person').press('Tab');
  await card.getByLabel('Land-offer qualification').fill('Offer allows for remediation scheme');
  await card.getByLabel('Land-offer qualification').press('Tab');
  await register.getByText('Land-offer schedule (1)', { exact: true }).click();
  await expect(register).toContainText('Disclosed subset already included in appraisal costs: £25,000.00');
  await card.getByLabel('Status for Contamination and remediation').selectOption('CLEARED');
  await expect(card.getByRole('button', { name: 'Confirm', exact: true })).toBeDisabled();
  await card.getByLabel('Clearance reason').fill('Investigation confirms clean ground');
  await card.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(card).toContainText('Previous estimate retained: £25,000.00');
  await expect(register).toContainText('cleared: 1');
  await card.getByLabel('Status for Contamination and remediation').selectOption('KNOWN');
  await card.getByLabel('Confirm amount to reinstate').fill('30000');
  await card.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(card.getByLabel('Abnormal amount')).toHaveValue('£30,000.00');
  await expect(register.getByLabel('Abnormals base allowance')).toHaveValue('10000');
  await register.getByLabel('Filter allocation').selectOption('PLOT_WORKS');
  await expect(card).toHaveCount(0);
  await register.getByLabel('Filter allocation').selectOption('ALL');
  await expect(card).toBeVisible();
  await register.getByRole('button', { name: 'Add standard abnormal checklist' }).click();
  await expect(register.locator('[data-site-cost-id]')).toHaveCount(18);
  await expect.poll(async () => { const raw = await page.evaluate(() => localStorage.getItem('qs-pro-appraisals-v1') || '[]'); return parseStoredJson<any[]>(raw)[0]?.options[0]?.costLines.find((line: {id: string}) => line.id === 'site-checklist-contamination')?.amount; }).toBe(30000);
  await register.getByLabel('Site costs summary').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'outputs/site-cost-register-review/register-review.png' });
  await smoke(page, 'appraisals-house-stage-abnormals').first().click();
  const overview = smoke(page, 'appraisals-site-costs-summary');
  await expect(overview).toContainText('Contamination and remediation');
  await expect(overview).toContainText('£30,000');
  await overview.getByRole('button', {name: 'Open Abnormals', exact: true}).click();
  await expect(register).toBeVisible();
  const reopened = await context.newPage();
  await reopened.goto('/');
  await smoke(reopened, 'rail-appraisals').click();
  await expect(smoke(reopened, 'appraisals-register-results')).toContainText('Site register review');
  const stored = parseStoredJson<any[]>(await reopened.evaluate(() => localStorage.getItem('qs-pro-appraisals-v1') || '[]'))[0].options[0];
  const element = stored.costLines.find((line: {id: string}) => line.id === 'site-checklist-contamination');
  expect(stored.abnormalBaseAllowance).toBe(10000);
  expect(element.siteCost.allocation).toBe('INFRASTRUCTURE');
  expect(element.siteCost.includeInLandOffer).toBe(true);
  expect(element.siteCost.responsiblePerson).toBe('Review QS');
  expect(element.siteCost.history.some((entry: {action: string}) => entry.action === 'Cleared')).toBe(true);
  expect(element.siteCost.history.some((entry: {action: string}) => entry.action === 'Reopened')).toBe(true);
  await reopened.close();
});


